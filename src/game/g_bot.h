/*
===========================================================================

NAVIGATION

The navigation graph is generated by flood-filling the map's collision
model with hull traces (the same traces player movement uses), starting
from every spawn point, buildable and teleporter destination. Nodes sit
on walkable floor on a regular grid; edges record how the step between
two nodes is made (walk, jump, drop, wall climb, ladder, teleport) and
which hull sizes fit through. Wall walking aliens get "climb" edges up
any vertical surface, so they use walls to reach ledges other classes
cannot.

===========================================================================
*/

#define NAV_MAX_NODES       32768
#define NAV_MAX_EDGES       ( NAV_MAX_NODES * 8 )
#define NAV_MAX_EXTRA       256       // teleporter edges, added after generation
#define NAV_HASH_SIZE       16384     // power of two
#define NAV_MAX_PATH        384

#define NAV_STEPSIZE        18.0f
#define NAV_MAX_DROP        1024.0f
#define NAV_MAX_CLIMB       512.0f

// hull classes: every player class maps to one of these
typedef enum
{
  NAV_HULL_SMALL,   // dretch
  NAV_HULL_MEDIUM,  // basilisks, grangers, marauders
  NAV_HULL_HUMAN,   // human
  NAV_HULL_DRAGOON, // dragoons
  NAV_HULL_LARGE,   // tyrant
  NAV_HULL_TALL,    // battlesuit: human width, extra height

  NAV_NUM_HULLS
} navHull_t;

// node flags
#define NAVN_HAZARD     0x01  // lava, slime, trigger_hurt, bottomless pit
#define NAVN_WATER      0x02
#define NAVN_EXTRA      0x04  // has entries in the extra (teleporter) edge list
#define NAVN_SEED       0x08  // created from a seed entity
#define NAVN_EDGE       0x10  // next to a fall into the void or a kill zone

// edge flags
#define NAVE_DROP       0x01  // walk off a ledge (dz < -STEPSIZE)
#define NAVE_CLIMB      0x02  // needs vertical ability: jump / wall climb / jetpack
#define NAVE_LADDER     0x04  // the climbed surface is a ladder
#define NAVE_TELEPORT   0x08
#define NAVE_DOOR       0x10  // passes through a (temporarily unlinked) door

typedef struct
{
  float           origin[ 3 ];  // point on the floor
  int             firstEdge;
  short           numEdges;       // (signed: q3asm can't store unsigned shorts)
  unsigned char   flags;
  unsigned char   hulls;        // bit per navHull_t that fits standing here
  short           cx, cy;       // grid cell
  int             hashNext;
} navNode_t;

typedef struct
{
  short           target;       // node number (NAV_MAX_NODES fits a signed short)
  unsigned char   flags;
  unsigned char   hulls;        // bit per navHull_t that can traverse
  short           dz;           // target.z - source.z
  short           climb;        // vertical clearance needed above source floor
  short           cost;         // travel cost (roughly distance in units)
  short           pad;
} navEdge_t;

typedef struct
{
  int             from;
  navEdge_t       edge;
} navExtraEdge_t;

// what a particular bot can traverse (filled from its class)
typedef struct
{
  navHull_t       hull;
  float           maxClimb;     // tallest climb without help
  float           maxDrop;      // longest drop considered safe
  qboolean        wallClimber;  // can climb any wall
  qboolean        ladders;
  qboolean        jetpack;
  team_t          team;         // for danger avoidance
} navCaps_t;

typedef enum
{
  NAVSTATE_NONE,       // no graph
  NAVSTATE_BUILDING,   // generation in progress
  NAVSTATE_READY
} navState_t;

extern navNode_t       navNodes[ NAV_MAX_NODES ];
