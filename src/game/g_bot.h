#define BOT_MAX_SKILL     10

typedef enum
{
  BROLE_ATTACK,     // push to the enemy base
  BROLE_DEFEND,     // hang around our own base
  BROLE_BUILDER,    // granger / construction kit
  BROLE_ROAM        // hunt enemy players wherever they are
} botRole_t;

typedef enum
{
  BGOAL_NONE,
  BGOAL_FIGHT,       // shooting / clawing an enemy we can see
  BGOAL_HUNT,        // moving toward an enemy we know about
  BGOAL_ATTACKBASE,  // moving toward an enemy structure
  BGOAL_DEFEND,      // patrolling our base
  BGOAL_ARMOURY,     // human: walking to an armoury to shop
  BGOAL_HEAL,        // walking to a medistation / booster / creep
  BGOAL_BUILD,       // walking to a build spot
  BGOAL_REPAIR,      // human builder repairing a structure
  BGOAL_EVOLVE,      // alien: find a safe spot to evolve
  BGOAL_FLEE,        // getting away from danger
  BGOAL_ROAM,        // wander to a random spot

  BGOAL_NUM
} botGoal_t;

typedef enum
{
  BMOVE_NONE,
  BMOVE_PATH,
  BMOVE_DIRECT
} botMoveMode_t;

// personality: drawn at random when the bot is added, steers the
// decision trees so a team of bots doesn't all do the same thing
typedef struct
{
  float           aggression;   // 0..1: rush vs hang back
  float           saver;        // 0..1: alien saves evos for big classes / human saves credits
  int             weaponPref;   // index into the human weapon preference tables
  int             alienPref;    // preferred line of evolution
} botPersonality_t;

typedef struct bot_s
{
  qboolean        inuse;
  int             clientNum;
  int             skill;
  team_t          wantTeam;     // TEAM_NONE == pick automatically
  botPersonality_t pers;

  // timing
  int             spawnedAt;
  int             nextDecision;
  int             nextTeamTry;
  int             nextClassTry;
  int             nextChat;

  // role and goal
  botRole_t       role;
  int             nextRoleCheck;
  int             goalFailCount;      // roam/defend goals in a row we couldn't path to
  int             lastGoalFail;
  botGoal_t       goal;
  int             goalEnt;          // entity number or -1
  vec3_t          goalPos;
  int             goalNode;
  int             goalSetTime;
  int             goalTimeout;
  int             forcedGoalUntil;  // botgoto
  vec3_t          forcedGoal;
  qboolean        forcedReached;

  // perception
  int             enemy;            // entity number or -1
  int             enemySeenTime;    // last time we had line of sight
  int             enemyFirstSeen;   // for reaction time
  vec3_t          enemyLastPos;
  vec3_t          enemyLastVel;
  int             lastAttacker;
  int             lastHurtTime;
  int             lastHealth;
  int             nextEnemyScan;

  // combat movement
  int             strafeDir;
  int             nextStrafeChange;

  // aim
  vec3_t          viewAngles;       // what we are looking at right now
  vec3_t          aimError;         // current aim offset (degrees)
  int             nextAimErrorTime;
  float           aimFactor;        // this bot's own spread around its skill (0.85 - 1.15)
  // where the current enemy was recently, for aim delay
#define BOT_AIM_HISTORY 32
  vec3_t          aimHist[ BOT_AIM_HISTORY ];
  int             aimHistTime[ BOT_AIM_HISTORY ];
  int             aimHistHead, aimHistCount, aimHistEnt;
  // emotes
  int             emoteAt;          // press the gesture button at this time
  int             nextEmote;
  int             lastScore;
  qboolean        aimLocked;        // crosshair is on target

  // navigation
  navCaps_t       caps;
  int             path[ NAV_MAX_PATH ];   // edge numbers
  int             pathLen;
  int             pathPos;
  int             pathGoalNode;
  int             pathStart;            // node the path starts from
  int             pathTime;
  int             pathFailTime;
  int             curNode;
  int             nextSmooth;
  int             badEdge;              // edge we got stuck on
  int             badEdgeUntil;
  botMoveMode_t   moveMode;

  // stuck detection
  vec3_t          stuckPos;
  int             stuckCheckTime;
  int             stuckCount;
  int             unstickUntil;
  float           unstickYaw;
  int             lastJumpTime;

  // the command being assembled this frame
  usercmd_t       cmd;
  float           moveYaw;          // yaw we want to move along
  qboolean        wantMove;
  qboolean        walk;
  int             upmove;
  int             buttons;
  int             lastButtons;
  qboolean        wantWallclimb;
  qboolean        forceView;        // movement needs to control the view this frame

  // abilities
  int             chargeStart;      // pounce / trample / lcannon charge start
  int             chargeFor;        // msec to hold the charge
  int             abilityCooldown;
  int             jetpackUntil;

  // human shopping
  int             lastBuyTime;
  int             creditsAtLastBuy;
  int             nextItemUse;

  // alien evolution
  int             nextEvolveTry;
  int             evolveFailures;

  // building
  int             buildType;          // buildable_t we are trying to build
  vec3_t          buildSpot;
  int             buildTries;
  int             nextBuildPlan;
  int             buildSettle;        // time we arrived at the spot
  int             buildPhase;         // 0 walking, 1 aiming, 2 placing
  float           buildYaw;
  int             buildPhaseTime;
  int             buildSpotIndex;     // defense spot being filled, or -1
  vec3_t          buildOrigin;        // where the structure will actually land
  int             repairEnt;
  int             nextBlasterSwap;

  // debugging
  qboolean        debug;
  int             nextDebugPrint;
  char            lastAction[ 64 ];
} bot_t;

